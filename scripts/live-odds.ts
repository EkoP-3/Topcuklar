/**
 * Fits the live win-chance model shown under the HP bars: plays many matches,
 * samples the features (src/sim/live.ts) every half second, and fits a logistic
 * regression against who actually won. Writes src/sim/livemodel.ts and prints a
 * calibration table. Re-run after balance changes (after scripts/odds.ts):
 *   bun scripts/live-odds.ts [matchesPerPair]
 */
import { writeFileSync } from "node:fs";
import { liveFeatures } from "../src/sim/live";
import { ROSTERS } from "../src/sim/rosters";
import type { FighterDef } from "../src/sim/types";
import { World } from "../src/sim/world";

const N = Number(process.argv[2] ?? 30);
const R: readonly FighterDef[] = ROSTERS.leaders;
const X: number[][] = [];
const Y: number[] = [];

for (let i = 0; i < R.length; i++) {
  for (let j = 0; j < R.length; j++) {
    const a = R[i];
    const b = R[j];
    if (!a || !b || i === j) continue;
    for (let s = 0; s < N; s++) {
      const world = new World(9000 + s, [a, b]);
      const rows: number[][] = [];
      let next = 0;
      let frames = 0;
      while (world.phase !== "over" && frames < 60 * 200) {
        world.advance(1 / 60);
        world.events.length = 0;
        frames++;
        if (world.phase === "fight" && world.time >= next) {
          next += 0.5;
          const x = liveFeatures(world);
          if (x) rows.push(x);
        }
      }
      for (const r of rows) {
        X.push(r);
        Y.push(world.winner === 0 ? 1 : 0);
      }
    }
  }
}

const k = X[0]?.length ?? 0;
const w = new Array<number>(k).fill(0);
w[1] = 1;
const sig = (z: number) => 1 / (1 + Math.exp(-z));
const predict = (x: number[], wt: number[]) =>
  sig(x.reduce((acc, v, i) => acc + v * (wt[i] ?? 0), 0));
// Full-batch gradient descent with a little momentum.
const vel = new Array<number>(k).fill(0);
for (let it = 0; it < 1500; it++) {
  const g = new Array<number>(k).fill(0);
  for (let n = 0; n < X.length; n++) {
    const x = X[n] ?? [];
    const e = predict(x, w) - (Y[n] ?? 0);
    for (let i = 0; i < k; i++) g[i] = (g[i] ?? 0) + e * (x[i] ?? 0);
  }
  for (let i = 0; i < k; i++) {
    vel[i] = 0.9 * (vel[i] ?? 0) - (0.5 * (g[i] ?? 0)) / X.length;
    w[i] = (w[i] ?? 0) + (vel[i] ?? 0);
  }
}

const brier = (wt: number[]) =>
  X.reduce((acc, x, n) => acc + (predict(x, wt) - (Y[n] ?? 0)) ** 2, 0) / X.length;
const priorOnly = [0, 1, 0, 0, 0, 0];
console.log(`samples: ${X.length}`);
console.log(`weights: ${w.map((v) => v.toFixed(3)).join(", ")}`);
console.log(
  `Brier: model ${brier(w).toFixed(4)}  vs pre-fight odds only ${brier(priorOnly).toFixed(4)}`,
);
console.log("calibration (predicted -> actual):");
for (let b = 0; b < 10; b++) {
  let n = 0;
  let won = 0;
  let sum = 0;
  for (let i = 0; i < X.length; i++) {
    const p = predict(X[i] ?? [], w);
    if (Math.min(9, Math.floor(p * 10)) !== b) continue;
    n++;
    sum += p;
    won += Y[i] ?? 0;
  }
  if (n > 0) {
    console.log(
      `  ${b * 10}-${b * 10 + 10}%: predicted ${((sum / n) * 100).toFixed(1)}%, actual ${((won / n) * 100).toFixed(1)}% (n=${n})`,
    );
  }
}

writeFileSync(
  new URL("../src/sim/livemodel.ts", import.meta.url),
  `// Generated by scripts/live-odds.ts (${N} matches per ordered pair) — do not edit by hand.
/** Weights for [bias, prior logit, HP lead, HP lead x time, ult left, domain owner]. */
export const LIVE_WEIGHTS: readonly number[] = [${w.map((v) => v.toFixed(4)).join(", ")}];
`,
);
console.log("wrote src/sim/livemodel.ts");
