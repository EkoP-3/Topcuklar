/**
 * Plays every pair of leaders many times (both spawn orders) and writes the win
 * chances shown on the "pick your side!" card to src/sim/odds.ts. Re-run after any
 * balance change:
 *   bun scripts/odds.ts [matchesPerPair]
 */
import { writeFileSync } from "node:fs";
import { ROSTERS } from "../src/sim/rosters";
import type { FighterDef } from "../src/sim/types";
import { World } from "../src/sim/world";

const N = Number(process.argv[2] ?? 400);
const R: readonly FighterDef[] = ROSTERS.leaders;

function winnerOf(seed: number, a: FighterDef, b: FighterDef): number {
  const world = new World(seed, [a, b]);
  let frames = 0;
  while (world.phase !== "over" && frames < 60 * 200) {
    world.advance(1 / 60);
    world.events.length = 0;
    frames++;
  }
  return world.winner;
}

const table: Record<string, number> = {};
for (let i = 0; i < R.length; i++) {
  for (let j = i + 1; j < R.length; j++) {
    const a = R[i];
    const b = R[j];
    if (!a || !b) continue;
    let wins = 0;
    for (let s = 0; s < N; s++) {
      const swap = s % 2 === 1;
      const w = winnerOf(5000 + s, swap ? b : a, swap ? a : b);
      if (w === (swap ? 1 : 0)) wins++;
    }
    table[`${a.id}|${b.id}`] = Math.round((wins / N) * 1000) / 1000;
    console.log(`${a.id} vs ${b.id}: ${Math.round((wins / N) * 100)}%`);
  }
}

const body = Object.entries(table)
  .map(([k, v]) => `  "${k}": ${v},`)
  .join("\n");
writeFileSync(
  new URL("../src/sim/odds.ts", import.meta.url),
  `// Generated by scripts/odds.ts (${N} matches per pair) — do not edit by hand.

/** Chance that the first leader beats the second ("a|b"). */
const ODDS: Record<string, number> = {
${body}
};

/** Pre-fight win chance (0..1) of leader \`a\` against \`b\`, or null when unknown. */
export function winChance(a: string, b: string): number | null {
  const direct = ODDS[\`\${a}|\${b}\`];
  if (direct !== undefined) return direct;
  const reverse = ODDS[\`\${b}|\${a}\`];
  return reverse !== undefined ? 1 - reverse : null;
}
`,
);
console.log("wrote src/sim/odds.ts");
